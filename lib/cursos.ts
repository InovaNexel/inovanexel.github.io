type CursoInput = Omit<Curso, "id">;

function slug(s: string) {
  return s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function c(duracao: Duracao, titulo: string, contexto?: string, importancia?: string, publico?: string): CursoInput {
  return { titulo, duracao, contexto, importancia, publico };
}

function trilha(t: Omit<Trilha, "cursos"> & { cursos: CursoInput[] }): Trilha {
  return { ...t, cursos: t.cursos.map((x) => ({ ...x, id: `${t.id}--${slug(x.titulo)}` })) };
}

