/** Link do WhatsApp com a mensagem já preenchida com o curso escolhido. */
export function whatsappCurso(curso?: Curso, trilha?: Trilha) {
  const texto = curso
    ? `Olá, Inova Nexel! Tenho interesse no curso "${curso.titulo}" (trilha ${trilha?.titulo}). Pode me passar as próximas turmas e como me inscrever?`
    : "Olá, Inova Nexel! Tenho interesse nos cursos de capacitação. Pode me ajudar a escolher uma trilha?";
  return `${site.whatsappHref}?text=${encodeURIComponent(texto)}`;
}
